/**
 * دالة مساعدة لتحديد معرف المجموعة لأي نوع عقار حالي أو تاريخي
 */
export function getGroupForPropertyType(typeName: string): PropertyGroupId {
  const cleanName = (typeName || '').trim();
  const found = INITIAL_PROPERTY_TYPES.find((t) => t.name === cleanName);
  if (found) return (found.categoryId || found.groupId || 'residential') as PropertyGroupId;

  // Fallbacks for legacy/varied spellings in historical data
  if (cleanName.includes('أرض') || cleanName.includes('فضاء') || cleanName.includes('زراع') || cleanName.includes('مزرعة')) {
    return 'lands';
  }
  if (cleanName.includes('محل') || cleanName.includes('معرض') || cleanName.includes('كافيه') || cleanName.includes('مطعم') || cleanName.includes('تجاري')) {
    return 'commercial';
  }
  if (cleanName.includes('مكتب') || cleanName.includes('عيادة') || cleanName.includes('شركة') || cleanName.includes('طبي') || cleanName.includes('مستشفى') || cleanName.includes('معمل')) {
    return 'admin_medical';
  }
  if (cleanName.includes('مخزن') || cleanName.includes('بدروم') || cleanName.includes('مصنع') || cleanName.includes('هنجر') || cleanName.includes('ثلاجة') || cleanName.includes('صناعي') || cleanName.includes('جراج')) {
    return 'industrial_storage';
  }
  return 'residential';
}

